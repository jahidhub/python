li = [1, 8, 7, 2, 21, 15]

li.reverse()  # [21, 15, 8, 7, 2, 1]

li.sort()  #  [1,2,7,8,15,21]


li.append(25)  # [1, 2, 7, 8, 15, 21, 25]

li.insert(4, 10)  # [1, 2, 7, 8, 10, 15, 21, 25]

li.pop(2)  # [1, 2, 8, 10, 15, 21, 25]

li.remove(21)  # [1, 2, 8, 10, 15, 25]

li[5] = 50

ul = type(li)

print(li)
print(ul)
